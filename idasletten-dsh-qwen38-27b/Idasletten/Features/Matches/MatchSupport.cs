using Idasletten.Data;
using Idasletten.Features.Common;
using Idasletten.Features.Players.Commands.AddPlayer;
using Idasletten.Features.Users.Commands.FindOrCreateUser;
using Idasletten.Models;
using Idasletten.Scoring;
using MediatR;
using Microsoft.EntityFrameworkCore;

namespace Idasletten.Features.Matches;

/// <summary>Shared plumbing for creating/attaching teams, players and results.</summary>
public static class MatchSupport
{
    /// <summary>Resolve a list of initials to tournament players, auto-creating users/players. Returns player ids in order.</summary>
    public static async Task<List<Guid>> ResolveInitialsAsync(
        AppDbContext db, ScoringEngine scoring, IMediator mediator, IPublisher publisher,
        Tournament tournament, IReadOnlyList<string> initials, bool mustBeActive, CancellationToken ct)
    {
        if (initials.Count != tournament.TeamSize)
            throw new FeatureException($"Each team needs exactly {tournament.TeamSize} player(s).");
        if (initials.Select(i => FindOrCreateUserCommandHandler.Normalize(i)).Distinct().Count() != initials.Count)
            throw new FeatureException("A player appears twice in the same team.");

        var ids = new List<Guid>();
        foreach (var raw in initials)
        {
            var username = FindOrCreateUserCommandHandler.Normalize(raw);
            var userId = await mediator.Send(new FindOrCreateUserCommand(raw, null), ct);
            var player = await db.TournamentPlayers
                .FirstOrDefaultAsync(p => p.TournamentId == tournament.Id && p.UserId == userId, ct);
            if (player is null)
            {
                if (mustBeActive)
                    await AddPlayerCommandHandler.GetActiveTournamentAsync(db, tournament.Id, ct);
                await AddPlayerCommandHandler.AddUserAsync(db, scoring, tournament, userId, publisher, ct);
                player = await db.TournamentPlayers
                    .FirstAsync(p => p.TournamentId == tournament.Id && p.UserId == userId, ct);
            }
            else if (tournament.ScoreSystem == ScoreSystem.Lives && player.Lives == 0)
            {
                var u = await db.Users.FirstAsync(x => x.Id == userId, ct);
                throw new FeatureException($"{u.Username} has no lives left and cannot play.");
            }
            ids.Add(player.Id);
        }
        return ids;
    }

    public static async Task<List<TournamentPlayer>> LoadPlayersAsync(AppDbContext db, List<Guid> playerIds, CancellationToken ct)
    {
        return await db.TournamentPlayers
            .Include(p => p.User)
            .Where(p => playerIds.Contains(p.Id))
            .ToListAsync(ct);
    }

    /// <summary>Next Order value for a new match in the tournament.</summary>
    public static async Task<int> NextOrderAsync(AppDbContext db, Guid tournamentId, CancellationToken ct)
    {
        var max = await db.TournamentMatches
            .Where(m => m.TournamentId == tournamentId)
            .Select(m => (int?)m.Order)
            .MaxAsync(ct);
        return (max ?? 0) + 1;
    }

    /// <summary>Create a team entity with the given players. Number/Name autogenerated.</summary>
    public static async Task<TournamentTeam> CreateTeamAsync(AppDbContext db, Tournament tournament, int number, List<Guid> playerIds, CancellationToken ct)
    {
        var team = new TournamentTeam
        {
            TournamentId = tournament.Id,
            Number = number,
            Name = $"Team {number}"
        };
        db.TournamentTeams.Add(team);
        await db.SaveChangesAsync(ct);
        foreach (var pid in playerIds)
        {
            db.TeamPlayers.Add(new TeamPlayer { TeamId = team.Id, TournamentPlayerId = pid });
        }
        await db.SaveChangesAsync(ct);
        return team;
    }
}
